const WFLH_L = { male: -0.3521, female: -0.3833 };

function normalizeSex(sex) {
  const value = String(sex || "").trim().toLowerCase();
  if (value.startsWith("f")) return "female";
  return "male";
}

// WHO LMS method: converts a raw measurement into a z-score against the
// L (skewness), M (median) and S (coefficient of variation) for that
// age/length/height.
function lmsZScore(x, l, m, s) {
  if (l === 0) return Math.log(x / m) / s;
  return (Math.pow(x / m, l) - 1) / (l * s);
}

// Age-indexed tables (WFA, LFA, HFA) are already at monthly resolution, so
// this is a direct lookup by month rather than an interpolation.
function rowAtMonth(table, ageInMonths, tableStartMonth) {
  const idx = Math.min(Math.max(Math.round(ageInMonths) - tableStartMonth, 0), table.length - 1);
  return table[idx];
}

// Length/height-indexed tables (WFL, WFH) are sampled every 0.5cm; a child's
// actual measurement rarely lands exactly on a step, so interpolate between
// the two nearest rows.
function rowAtStep(table, x, start, step) {
  const pos = (x - start) / step;
  const clamped = Math.min(Math.max(pos, 0), table.length - 1);
  const lo = Math.floor(clamped);
  const hi = Math.min(lo + 1, table.length - 1);
  const frac = clamped - lo;
  const [m0, s0] = table[lo];
  const [m1, s1] = table[hi];
  return [m0 + (m1 - m0) * frac, s0 + (s1 - s0) * frac];
}

function weightForAgeZ(sex, ageInMonths, weightKg) {
  const table = normalizeSex(sex) === "female" ? WFA_GIRLS : WFA_BOYS;
  const [l, m, s] = rowAtMonth(table, ageInMonths, 0);
  return lmsZScore(weightKg, l, m, s);
}

function heightForAgeZ(sex, ageInMonths, heightCm) {
  const female = normalizeSex(sex) === "female";
  if (ageInMonths < 24) {
    const [m, s] = rowAtMonth(female ? LFA_GIRLS : LFA_BOYS, ageInMonths, 0);
    return lmsZScore(heightCm, 1, m, s);
  }
  const [m, s] = rowAtMonth(female ? HFA_GIRLS : HFA_BOYS, ageInMonths, 24);
  return lmsZScore(heightCm, 1, m, s);
}

function weightForHeightZ(sex, ageInMonths, weightKg, heightCm) {
  const female = normalizeSex(sex) === "female";
  const l = female ? WFLH_L.female : WFLH_L.male;
  if (ageInMonths < 24) {
    const [m, s] = rowAtStep(female ? WFL_GIRLS : WFL_BOYS, heightCm, WFL_START, WFL_STEP);
    return lmsZScore(weightKg, l, m, s);
  }
  const [m, s] = rowAtStep(female ? WFH_GIRLS : WFH_BOYS, heightCm, WFH_START, WFH_STEP);
  return lmsZScore(weightKg, l, m, s);
}

